import { describe, expect, it } from 'vitest';
import { getSourceFiles, vaultRelativePath, writeGeneratedFile } from '../../src/engine/VaultFiles';
import { createMockApp } from '../helpers/vault';

const output = '<!-- Generated by Knowledge Forge. -->\nreport';
describe('generated vault output', () => {
 it.each(['.kg-forge', 'outputs/.hidden', 'out/.report.md'])('rejects hidden Vault output %s', async path => {
  const { app } = createMockApp({});
  await expect(writeGeneratedFile(app.vault, path, 'report.md', output)).rejects.toThrow('hidden');
  expect(app.vault.create).not.toHaveBeenCalled();
 });
 it.each(['../notes','/tmp/output','C:\\notes','.','reports/../notes','\u0000bad'])('rejects unsafe folder %s', async path => {
  const { app } = createMockApp({});
  await expect(writeGeneratedFile(app.vault, path, 'report.md', output)).rejects.toThrow('vault-relative');
  expect(app.vault.create).not.toHaveBeenCalled();
 });
 it('normalises separators and creates nested directories', async () => {
  const { app, contents } = createMockApp({});
  const file = await writeGeneratedFile(app.vault, 'exports\\knowledge', 'concepts/Topic.md.triples.json', output);
  expect(file.path).toBe('exports/knowledge/concepts/Topic.md.triples.json');
  expect(contents.get(file.path)).toBe(output);
  expect(vaultRelativePath('exports//knowledge/')).toBe('exports/knowledge');
 });
 it('updates its own generated output atomically', async () => {
  const { app, contents } = createMockApp({ 'out/report.md': output });
  await writeGeneratedFile(app.vault, 'out', 'report.md', output + ' updated');
  expect(app.vault.process).toHaveBeenCalledTimes(1);
  expect(contents.get('out/report.md')).toBe(output + ' updated');
 });
 it('preserves an ordinary note at the output target', async () => {
  const { app, contents } = createMockApp({ 'out/report.md': 'My important notes' });
  await expect(writeGeneratedFile(app.vault, 'out', 'report.md', output)).rejects.toThrow('Refusing to overwrite');
  expect(contents.get('out/report.md')).toBe('My important notes');
 });
 it('rejects a file in a required directory and the host configuration folder', async () => {
  const { app, contents } = createMockApp({ 'out.md': 'Keep' });
  await expect(writeGeneratedFile(app.vault, 'out.md/sub', 'report.md', output)).rejects.toThrow('is a file');
  await expect(writeGeneratedFile(app.vault, '.obsidian/plugins', 'report.md', output)).rejects.toThrow('configuration');
  expect(contents.get('out.md')).toBe('Keep');
 });
 it('excludes only the configured output subtree from source scans', () => {
  const { app } = createMockApp({ 'out/report.md': output, 'out/notes/Topic.md': '', 'outside/Topic.md': '', 'outlier.md': '' });
  expect(getSourceFiles(app.vault, 'out').map(f => f.path)).toEqual(['outside/Topic.md','outlier.md']);
 });
});
