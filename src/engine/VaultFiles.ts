import { normalizePath, TFile, TFolder, type Vault } from 'obsidian';

/** Validate before normalisation so parent traversal cannot be hidden. */
export function vaultRelativePath(value: string): string {
	const path = value.trim().replace(/\\/g, '/');
	if (!path || path.startsWith('/') || /^[a-zA-Z]:/.test(path)
		|| path.split('/').some(part => part === '..' || part === '.')
		|| path.includes('\0')) {
		throw new Error('Choose a non-empty vault-relative path without parent traversal.');
	}
	return normalizePath(path).replace(/\/$/, '');
}

export function getSourceFiles(vault: Vault, cacheFolder: string): TFile[] {
	const folder = vaultRelativePath(cacheFolder);
	return vault.getMarkdownFiles().filter(file => file.path !== folder && !file.path.startsWith(`${folder}/`));
}

/** Generated output is confined to its configured folder, never the vault root. */
export async function writeGeneratedFile(
	vault: Vault, cacheFolder: string, relativePath: string, content: string,
): Promise<TFile> {
	const folder = vaultRelativePath(cacheFolder);
	const configDirectory = vault.configDir.toLowerCase();
	if (folder.toLowerCase() === configDirectory || folder.toLowerCase().startsWith(`${configDirectory}/`)) {
		throw new Error('Choose an output folder outside the Obsidian configuration directory.');
	}
	if ([...folder.split('/'), ...relativePath.replace(/\\/g, '/').split('/')].some(part => part.startsWith('.'))) {
		throw new Error('Choose visible output paths: hidden files and folders are not accessible through the Obsidian Vault API.');
	}
	const name = vaultRelativePath(relativePath);
	const path = `${folder}/${name}`;
	const parts = path.split('/');
	for (let i = 1; i < parts.length; i++) {
		const directory = parts.slice(0, i).join('/');
		const existing = vault.getAbstractFileByPath(directory);
		if (existing && !(existing instanceof TFolder)) {
			throw new Error(`Cannot write output: "${directory}" is a file. Choose a separate output folder.`);
		}
		if (!existing) {
			try {
				await vault.createFolder(directory);
			} catch (error) {
				// Another command may have created the same folder meanwhile.
				if (!(vault.getAbstractFileByPath(directory) instanceof TFolder)) throw error;
			}
		}
	}
	const existing = vault.getAbstractFileByPath(path);
	if (existing instanceof TFile) {
		await vault.process(existing, previous => {
			if (!isGeneratedContent(previous)) {
				throw new Error(`Refusing to overwrite "${path}": it is not a Knowledge Forge output. Choose a separate output folder.`);
			}
			return content;
		});
		return existing;
	}
	if (existing) throw new Error(`Cannot write output: "${path}" is a folder.`);
	return vault.create(path, content);
}

/** Recognise our current marker and the original plugin's output formats. */
function isGeneratedContent(content: string): boolean {
	if (content.startsWith('<!-- Generated by Knowledge Forge. -->')
		|| content.startsWith('// KG Forge Cypher Export')
		|| content.startsWith('# KG Forge Schema Validation Report\n')
		|| content.startsWith('# KG Forge Dataview Queries\n')) return true;
	try {
		const data = JSON.parse(content) as { generator?: string; file?: unknown; triples?: unknown };
		return data.generator === 'kg-forge' || (typeof data.file === 'string' && Array.isArray(data.triples));
	} catch { return false; }
}
