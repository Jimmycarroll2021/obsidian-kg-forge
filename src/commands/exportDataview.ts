import { Notice, Plugin, TFile } from 'obsidian';
import type { ForgeSettings } from '../settings';

type PluginWithSettings = Plugin & { settings: ForgeSettings };

const COMMAND_ID = 'export-dataview';
const COMMAND_NAME = 'Generate Dataview query templates';

/**
 * Register the "Generate Dataview queries" command.
 *
 * Creates a markdown note containing ready-to-run Dataview queries that mirror
 * the current folder→fileClass master map and provenance requirements. This
 * lets users keep using Dataview while KG Forge owns the schema contract.
 */
export function registerExportDataviewCommand(plugin: Plugin): void {
	plugin.addCommand({
		id: COMMAND_ID,
		name: COMMAND_NAME,
		callback: async () => {
			try {
				await generateDataviewQueries(plugin as PluginWithSettings);
			} catch (err) {
				const message = err instanceof Error ? err.message : String(err);
				console.error(`[KG Forge] ${COMMAND_NAME} failed`, err);
				new Notice(`KG Forge: Dataview export failed — ${message}`);
			}
		},
	});
}

async function generateDataviewQueries(plugin: PluginWithSettings): Promise<void> {
	const { settings } = plugin;
	const vault = plugin.app.vault;

	const lines: string[] = [
		'# KG Forge Dataview Queries',
		'',
		'Generated by **KG Forge** from the current folder→fileClass master map.',
		'Run these inside any note or in the Dataview query console.',
		'',
	];

	const mappings = Object.entries(settings.fileClassMappings);
	if (mappings.length === 0) {
		lines.push('> No folder→fileClass mappings configured yet. Add them in KG Forge settings.');
	} else {
		for (const [folder, fileClass] of mappings) {
			lines.push(`## ${fileClass} notes (${folder}/)`, '');
			lines.push('```dataview');
			lines.push('TABLE');
			lines.push('  file.link AS Note,');
			lines.push('  fileClass AS FileClass,');
			lines.push('  source AS Source,');
			lines.push('  source_ids AS SourceIDs');
			lines.push(`FROM "${folder}"`);
			lines.push('WHERE fileClass');
			lines.push('SORT file.name ASC');
			lines.push('```');
			lines.push('');
		}
	}

	lines.push('## Notes missing provenance', '');
	lines.push('```dataview');
	lines.push('TABLE file.link AS Note, fileClass AS FileClass');
	lines.push('WHERE (!source AND !source_ids) OR !fileClass');
	lines.push('SORT file.name ASC');
	lines.push('```');
	lines.push('');

	lines.push('## Breadcrumbs edges', '');
	lines.push('Lists notes that explicitly declare typed Breadcrumbs relationships.');
	lines.push('');
	for (const field of ['up', 'down', 'same', 'next', 'prev', 'source', 'requires', 'enables', 'related_to']) {
		lines.push(`### ${field}::`);
		lines.push('```dataview');
		lines.push('TABLE file.link AS Note, ' + field + ' AS `' + field + '`');
		lines.push('WHERE ' + field);
		lines.push('SORT file.name ASC');
		lines.push('```');
		lines.push('');
	}

	const content = lines.join('\n');
	const outPath = `${normalizePath(settings.cacheFolder)}/dataview-queries.md`;

	const existing = vault.getAbstractFileByPath(outPath);
	if (existing instanceof TFile) {
		await vault.modify(existing, content);
	} else {
		await vault.create(outPath, content);
	}

	new Notice(`KG Forge: Dataview queries written to ${outPath}`);
}

function normalizePath(path: string): string {
	return path.replace(/\/+/g, '/').replace(/\/$/, '') || '.';
}
